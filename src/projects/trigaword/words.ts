export type WordLength = 2 | 3 | 4 | 5 | 6 | 7 | 8

const WORD_LISTS: Record<WordLength, string[]> = {
  2: WORDS_2,
  3: WORDS_3,
  4: WORDS_4,
  5: WORDS_5,
  6: WORDS_6,
  7: WORDS_7,
  8: WORDS_8,
}

export const ROW_LENGTHS: WordLength[] = [2, 3, 4, 5, 6, 7, 8]

export function wordsForLength(length: WordLength): string[] {
  return WORD_LISTS[length]
}

export function randomWord(length: WordLength): string {
  const words = WORD_LISTS[length]
  return words[Math.floor(Math.random() * words.length)]
}

// --- Puzzle generation ---
// Rows are independent words (no anagram-chain relationship needed), so
// the pool is simply the concatenation of every row's non-first letters,
// shuffled. Since the pool is built directly from the chosen words, it is
// correct-by-construction: no reachability/solvability concerns.

export interface PoolTile {
  id: string
  char: string
}

export interface Row {
  word: string
  given: string
}

export interface Puzzle {
  rows: Row[]
  pool: PoolTile[]
}

function shuffle<T>(items: T[]): T[] {
  const arr = [...items]
  for (let i = arr.length - 1; i > 0; i--) {
    const j = Math.floor(Math.random() * (i + 1))
    ;[arr[i], arr[j]] = [arr[j], arr[i]]
  }
  return arr
}

export function buildPuzzle(): Puzzle {
  const rows: Row[] = ROW_LENGTHS.map((length) => {
    const word = randomWord(length)
    return { word, given: word[0] }
  })

  let tileId = 0
  const pool: PoolTile[] = shuffle(
    rows.flatMap((row) =>
      row.word
        .slice(1)
        .split('')
        .map((char) => ({ id: `t${tileId++}`, char })),
    ),
  )

  return { rows, pool }
}
